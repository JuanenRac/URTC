"""Keeps the "current state" block of VERSION_CHECKLIST.txt in step with the project manifest.

The checklist is written by hand, but the table of the versions that exist today must never be:
this tool writes it from `urtc.project.json` (the project version and every entry of `components[]`,
with the file and the prefix that hold each version), between two marker lines. `bump.py` runs it
after raising a version.

    python tools/version_checklist_state.py          # rewrite the block
    python tools/version_checklist_state.py --check  # exit 1 when the block is out of date
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "urtc.project.json"
CHECKLIST = ROOT / "VERSION_CHECKLIST.txt"
BEGIN = "# VERSION_STATE_BEGIN (generated by tools/version_checklist_state.py - do not edit by hand)"
END = "# VERSION_STATE_END"


def build_block(manifest: dict) -> str:
    lines = [BEGIN, "CURRENT VERSIONS (from urtc.project.json)", f"  project   {manifest['version']}"]
    for component in manifest.get("components", []):
        source = component.get("source", {})
        where = f"{source.get('file', '?')} ({source.get('prefix', '?')}_MAJOR/MINOR/PATCH)"
        lines.append(f"  {component['name']:<22} {component['version']:<8} {component.get('target', ''):<12} {where}")
    lines.append(END)
    return "\n".join(lines)


def rewrite(text: str, block: str) -> str:
    text = text.replace("\r\n", "\n")
    if BEGIN in text and END in text:
        start = text.index(BEGIN)
        stop = text.index(END, start) + len(END)
        return text[:start] + block + text[stop:]
    # first time: the block goes after the title banner (the first three lines)
    head, _, rest = text.partition("\n")
    second, _, rest = rest.partition("\n")
    third, _, rest = rest.partition("\n")
    return "\n".join([head, second, third, "", block, "", rest.lstrip("\n")])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when the block is out of date")
    args = parser.parse_args(argv)
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    current = CHECKLIST.read_bytes().decode("utf-8")
    wanted = rewrite(current, build_block(manifest))
    if current.replace("\r\n", "\n") == wanted:
        print("VERSION_CHECKLIST=CURRENT")
        return 0
    if args.check:
        print("VERSION_CHECKLIST=STALE (run python tools/version_checklist_state.py)", file=sys.stderr)
        return 1
    CHECKLIST.write_bytes(wanted.replace("\n", "\r\n" if "\r\n" in current else "\n").encode("utf-8"))
    print("VERSION_CHECKLIST=UPDATED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
