static uint8_t *flash_mem(uint32_t size, uint32_t *addr)
{
    uint8_t *p = mmap(0, size, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_32BIT, -1, 0);
    if (p == MAP_FAILED) return 0;
    *addr = (uint32_t)(uintptr_t)p;
    return p;
}

void run_bootloader_crypto_tests(int *failures)
{
    uint32_t addr = 0;
    uint8_t *flash = flash_mem(16384, &addr);
    if (!flash) { printf("  SKIP: cannot map low memory\n"); return; }
    for (uint32_t i = 0; i < 16384; i++) flash[i] = (uint8_t)((i * 7 + 3) & 0xFF);

    for (unsigned c = 0; c < sizeof(cases) / sizeof(cases[0]); c++) {
        uint8_t out[32];
        char label[160];
        memset(out, 0xEE, sizeof out);
        if (cases[c].pattern_len >= 0) {
            hmac_sha256_flash_region(cases[c].key, cases[c].key_len, addr, (uint32_t)cases[c].pattern_len, out);
        } else {
            memcpy(flash + 12000, cases[c].msg, strlen(cases[c].msg));
            hmac_sha256_flash_region(cases[c].key, cases[c].key_len, addr + 12000, (uint32_t)strlen(cases[c].msg), out);
        }
        snprintf(label, sizeof label, "HMAC-SHA256: %s", cases[c].name);
        TEST_ASSERT(memcmp(out, cases[c].want, 32) == 0, label);
    }

    // The watchdog is refreshed while hashing a long region (the backup slot
    // is 112 KiB), and the digest does not depend on how often that happens.
    fake_iwdg_refreshes = 0;
    uint8_t sink[32];
    hmac_sha256_flash_region(cases[3].key, cases[3].key_len, addr, 10000, sink);
    TEST_ASSERT(fake_iwdg_refreshes >= 2, "long hash refreshes the independent watchdog");

    // Verification semantics: a flipped bit anywhere changes the digest, the
    // comparison accepts only an exact match and does not stop at the first
    // differing byte.
    uint8_t good[32], bad[32];
    hmac_sha256_flash_region(cases[3].key, cases[3].key_len, addr, 300, good);
    flash[299] ^= 0x01;
    hmac_sha256_flash_region(cases[3].key, cases[3].key_len, addr, 300, bad);
    flash[299] ^= 0x01;
    TEST_ASSERT(memcmp(good, bad, 32) != 0, "one flipped bit in the image changes the signature");
    TEST_ASSERT(hmac_constant_time_compare(good, good, 32) == 1, "identical digests compare equal");
    TEST_ASSERT(hmac_constant_time_compare(good, bad, 32) == 0, "different digests compare unequal");
    for (int pos = 0; pos < 32; pos++) {
        uint8_t t[32];
        memcpy(t, good, 32);
        t[pos] ^= 0x80;
        if (hmac_constant_time_compare(good, t, 32) != 0) {
            TEST_ASSERT(0, "a single differing byte must be rejected at every position");
            break;
        }
    }
    TEST_ASSERT(hmac_constant_time_compare(good, bad, 0) == 1, "zero-length compare is trivially equal");
    uint8_t other_key[32];
    memset(other_key, 0x02, sizeof other_key);
    hmac_sha256_flash_region(other_key, 32, addr, 300, bad);
    TEST_ASSERT(memcmp(good, bad, 32) != 0, "a different key gives a different signature");
    munmap(flash, 16384);
}

int main(void)
{
    int failures = 0;
    printf("URTC host logic tests - bootloader_crypto.c\n");
    run_bootloader_crypto_tests(&failures);
    if (failures == 0) {
        printf("  OK   all bootloader crypto host tests passed\n");
        return 0;
    }
    printf("  %d assertion(s) failed\n", failures);
    return 1;
}
